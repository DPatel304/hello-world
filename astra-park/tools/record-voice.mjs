/* Records Last Known Position's lines with ElevenLabs, once, into
   src/audio/voice-lines.js - which ships in the game, so the laptop never
   calls ElevenLabs and never needs the key.

     node tools/record-voice.mjs          record what's new or changed
     node tools/record-voice.mjs --dry    just list what would be recorded
     node tools/record-voice.mjs --prune  drop recordings of lines no longer said

   The key is never read here: the requests go through curl, and the
   network proxy this runs behind adds it (set ELEVENLABS_API_KEY to send
   one yourself). Lines already recorded are kept as they are; lines no
   longer in the game are dropped. Needs curl and ffmpeg. */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { lines } from './voice-script.mjs';

const OUT = new URL('../src/audio/voice-lines.js', import.meta.url);
const MODEL = 'eleven_v3';
/* Who sounds like what: Nova, Sarah (warm, confident); the robots, Brian,
   pitched down and given a metallic ring afterwards (ffmpeg). */
export const CAST = {
  nova: { voice: 'EXAVITQu4vr4xnSDxMaL', stability: 0.5 },
  robot: { voice: 'nPczCjzI2devNBz1zQrb', stability: 1.0,
    fx: 'asetrate=44100*0.82,aresample=44100,aecho=0.8:0.6:12|24:0.4|0.3,tremolo=f=55:d=0.35,highpass=f=120,volume=1.3' }
};

/* How she says it: a delivery note for the model, never part of the line. */
export function delivery(text, who){
  if (who === 'robot') return '[robotic, flat monotone]';
  if (/^shh/i.test(text)) return '[whispers]';
  if (/great|nice|brave|amazing|super|brilliant|likes you|what a ride|okay!|made it|level up|gold pick|thank you|room clear|all of them|green across/i.test(text)) return '[warmly]';
  if (/^(the sweeper's down|treasure!|there it is)/i.test(text)) return '[excited]';
  if (/^(this is commander|your suits|my scans|the ship's still|that surge)/i.test(text)) return '[serious]';
  return '[urgent]';
}
/* A few said with more than one note, the way the moment goes. */
const SCRIPTED = {
  'Crew, do you read me? ...You\'re okay! Now, on your feet. Follow the path and I\'ll talk you through it.':
    '[serious] Crew, do you read me? ... [relieved] You\'re okay! [firm] Now, on your feet. Follow the path and I\'ll talk you through it.'
};
/* (the robots, with pauses between their words) */
const said = (text, who) => SCRIPTED[text] || `${delivery(text, who)} ${who === 'robot' ? text.replace(/\. /g, '. ... ') : text}`;

function load(){
  if (!existsSync(OUT)) return {};
  const m = readFileSync(OUT, 'utf8').match(/export const LINES = (\{[^]*\});/);
  return m ? JSON.parse(m[1]) : {};
}

function record(text, who, dir){
  const c = CAST[who], raw = join(dir, 'raw.mp3'), out = join(dir, 'out.mp3'), body = join(dir, 'body.json');
  writeFileSync(body, JSON.stringify({ text: said(text, who), model_id: MODEL, voice_settings: { stability: c.stability } }));
  const key = process.env.ELEVENLABS_API_KEY ? ['-H', `xi-api-key: ${process.env.ELEVENLABS_API_KEY}`] : [];
  const code = execFileSync('curl', ['-sS', '-X', 'POST', `https://api.elevenlabs.io/v1/text-to-speech/${c.voice}?output_format=mp3_44100_64`,
    '-H', 'Content-Type: application/json', ...key, '--data', `@${body}`, '-o', raw, '-w', '%{http_code}']).toString();
  if (code !== '200') throw new Error(`ElevenLabs said ${code} for "${text}": ${readFileSync(raw, 'utf8').slice(0, 300)}`);
  /* small: mono, 22 kHz, 32 kbps - plenty for a voice on the radio */
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-i', raw, ...(c.fx ? ['-af', c.fx] : []), '-ac', '1', '-ar', '22050', '-b:a', '32k', out]);
  const secs = +execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', out]).toString().trim();
  return { who, secs: Math.round(secs * 100) / 100, mp3: readFileSync(out).toString('base64') };
}

function save(all){
  const sorted = Object.fromEntries(Object.keys(all).sort().map(k => [k, all[k]]));
  writeFileSync(OUT, `/* Generated by tools/record-voice.mjs - don't edit by hand.
   Last Known Position's lines, recorded with ElevenLabs (${MODEL}):
   the exact line -> who says it, how long it is (seconds), and the mp3. */
export const LINES = ${JSON.stringify(sorted, null, 0).replace(/,"(?=[^"]*":\{)/g, ',\n"')};
`);
}

if (import.meta.url === `file://${process.argv[1]}`){
  const want = lines(), have = load(), dry = process.argv.includes('--dry');
  const keep = {}, todo = [];
  for (const { who, text } of want) (have[text] && have[text].who === who ? (keep[text] = have[text]) : todo.push({ who, text }));
  console.log(`${want.length} lines: ${Object.keys(keep).length} recorded already, ${todo.length} to record (${todo.reduce((n, l) => n + l.text.length, 0)} characters)`);
  if (dry){ todo.forEach(l => console.log(' ', l.who, delivery(l.text, l.who), l.text)); process.exit(0); }
  /* --prune: just drop the recordings of lines no longer in the game */
  if (process.argv.includes('--prune')){ save(keep); console.log('kept', Object.keys(keep).length); process.exit(0); }
  const dir = mkdtempSync(join(tmpdir(), 'voice-'));
  try {
    for (const [k, l] of todo.entries()){
      keep[l.text] = record(l.text, l.who, dir);
      console.log(`${k + 1}/${todo.length}  ${keep[l.text].secs}s  ${l.text}`);
      if (k % 10 === 9) save(keep);
    }
  } finally { save(keep); rmSync(dir, { recursive: true, force: true }); }
}
